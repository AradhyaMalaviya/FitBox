// Builds a curated, secret-free knowledge pack for the project-assistant chatbot.
// Usage: node scripts/build-project-knowledge.mjs
// Output: src/data/projectKnowledge.ts (exports PROJECT_KNOWLEDGE + PROJECT_KNOWLEDGE_META)
// Never reads .env files or secrets — only docs, routes, and structural summaries.

import { readFile, writeFile, readdir, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "src", "data", "projectKnowledge.ts");

const MAX_PER_FILE = 6000;
const MAX_TOTAL = 30000;

const readCapped = async (rel, cap = MAX_PER_FILE) => {
  try {
    const full = path.join(ROOT, rel);
    const content = await readFile(full, "utf8");
    const capped = content.length > cap ? content.slice(0, cap) + `\n…(truncated ${content.length - cap} chars)` : content;
    return { rel, content: capped, fullLength: content.length, missing: false };
  } catch {
    return { rel, content: "(missing)", fullLength: 0, missing: true };
  }
};

const listFiles = async (relDir, depth = 0, maxDepth = 3) => {
  const out = [];
  if (depth > maxDepth) return out;
  let entries = [];
  try {
    entries = await readdir(path.join(ROOT, relDir));
  } catch {
    return out;
  }
  for (const name of entries.sort()) {
    // Skip noise / secrets / build output
    if (["node_modules", "dist", "dist-ssr", ".git", ".hermes", "supabase/.temp"].some((s) => `${relDir}/${name}`.includes(s))) continue;
    if (name.startsWith(".env")) continue;
    if (name === ".hermes") continue;
    const rel = `${relDir}/${name}`.replace(/^\.\//, "");
    let st;
    try {
      st = await stat(path.join(ROOT, rel));
    } catch {
      continue;
    }
    if (st.isDirectory()) {
      out.push(`${"  ".repeat(depth)}${name}/`);
      out.push(...(await listFiles(rel, depth + 1, maxDepth)));
    } else {
      out.push(`${"  ".repeat(depth)}${name}`);
    }
    if (out.length > 400) break;
  }
  return out;
};

const extractRoutes = (appTsx) => {
  // Match both direct and wrapper-wrapped route patterns
  const matches = [...appTsx.matchAll(/<Route\s+path="([^"]+)"\s+element=\{<(?:(?:Public|Protected)Route>\s*<)?(\w+)/g)];
  if (!matches.length) return "(could not parse routes)";
  return matches.map((m) => `${m[1]} -> ${m[2]}`).join("\n");
};

const main = async () => {
  const docs = [
    await readCapped("README.md", 4000),
    await readCapped("FitBox_PRD.md", 5000),
    await readCapped("FitBox_Synopsis.md", 5000),
    await readCapped("AGENTS.md", 6000),
    await readCapped("src/App.tsx", 6000),
    await readCapped("src/lib/env.ts", 1000),
    await readCapped("supabase/config.toml", 1000),
    await readCapped("package.json", 2000),
  ];

  const appDoc = docs.find((d) => d.rel === "src/App.tsx");
  const routes = appDoc && !appDoc.missing ? extractRoutes(appDoc.content) : "(missing src/App.tsx)";

  const tree = await listFiles("src", 0, 3);
  const functions = await listFiles("supabase/functions", 0, 1);
  const migrations = (await listFiles("supabase/migrations", 0, 1)).slice(0, 40);

  const sections = [
    "# FitBox project knowledge (auto-generated, secret-free)",
    "",
    "## What this app is",
    docs.find((d) => d.rel === "AGENTS.md")?.content ?? "(missing)",
    "",
    "## Routes (src/App.tsx)",
    routes,
    "",
    "## Env contract (src/lib/env.ts — names only, no values)",
    docs.find((d) => d.rel === "src/lib/env.ts")?.content ?? "(missing)",
    "",
    "## Supabase functions",
    functions.join("\n") || "(none)",
    "config:\n" + (docs.find((d) => d.rel === "supabase/config.toml")?.content ?? "(missing)"),
    "",
    "## Migrations (names only)",
    migrations.join("\n") || "(none)",
    "",
    "## src/ tree (depth 3, truncated)",
    tree.slice(0, 220).join("\n"),
    "",
    "## README (truncated)",
    docs.find((d) => d.rel === "README.md")?.content ?? "(missing)",
    "",
    "## PRD (truncated)",
    docs.find((d) => d.rel === "FitBox_PRD.md")?.content ?? "(missing)",
    "",
    "## Synopsis (truncated)",
    docs.find((d) => d.rel === "FitBox_Synopsis.md")?.content ?? "(missing)",
  ];

  let knowledge = sections.join("\n");
  if (knowledge.length > MAX_TOTAL) {
    knowledge = knowledge.slice(0, MAX_TOTAL) + `\n…(truncated ${sections.join("\n").length - MAX_TOTAL} chars total)`;
  }

  const ts = `// AUTO-GENERATED by scripts/build-project-knowledge.mjs — do not hand-edit.\n// Regenerate: npm run build:knowledge\n// Secret-free: contains docs, routes, and file names only. No .env values.\nexport const PROJECT_KNOWLEDGE_META = {\n  generatedAt: ${JSON.stringify(new Date().toISOString())},\n  maxChars: ${MAX_TOTAL},\n  chars: ${knowledge.length},\n} as const;\n\nexport const PROJECT_KNOWLEDGE = ${JSON.stringify(knowledge)};\n`;
  await writeFile(OUT, ts, "utf8");
  console.log(`Wrote ${path.relative(ROOT, OUT)} (${knowledge.length} chars)`);
};

await main();
